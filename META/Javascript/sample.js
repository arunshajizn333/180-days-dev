var Day = "Sunday";

switch(Day){
    case "Monday":
        console.log('Do something');
        break;
    case "Tuesday":
        console.log('Do something else');
        break;      
    case "Wednesday":
        console.log('Do another thing');
        break;
    case "Thursday": 
        console.log('Do something different');  
        break;
    case "Sunday":
        console.log('Do nothing');
        break;
    default:
        console.log('Invalid day');
        break;

    
}